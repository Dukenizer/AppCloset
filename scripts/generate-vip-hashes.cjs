/**
 * Reads VIP CSV (code, tier, ...) + ARTCLOSET_VIP_SALT and writes hash lists only.
 * Formula: SHA-256(salt + uppercase(code)) hex.
 *
 * Usage:
 *   set ARTCLOSET_VIP_SALT=... && node scripts/generate-vip-hashes.cjs [csvPath]
 */
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const salt = process.env.ARTCLOSET_VIP_SALT?.trim();
if (!salt) {
  console.error('Missing ARTCLOSET_VIP_SALT environment variable.');
  process.exit(1);
}

const defaultCsv = path.join(
  process.env.USERPROFILE || process.env.HOME || '',
  'Downloads',
  'artcloset_vip_codes.csv',
);
const csvPath = process.argv[2] || defaultCsv;

if (!fs.existsSync(csvPath)) {
  console.error(`CSV not found: ${csvPath}`);
  process.exit(1);
}

function hashCode(code) {
  return crypto.createHash('sha256').update(salt + code.toUpperCase().trim(), 'utf8').digest('hex');
}

const text = fs.readFileSync(csvPath, 'utf8');
const lines = text.split(/\r?\n/).filter((l) => l.trim());
const header = lines[0].split(',').map((h) => h.trim());
const codeIdx = header.indexOf('code');
const tierIdx = header.indexOf('tier');
if (codeIdx < 0 || tierIdx < 0) {
  console.error('CSV must include code and tier columns.');
  process.exit(1);
}

const vip1 = [];
const vip2 = [];
for (let i = 1; i < lines.length; i++) {
  const cols = lines[i].split(',');
  const code = (cols[codeIdx] || '').trim();
  const tier = (cols[tierIdx] || '').trim().toUpperCase();
  if (!/^[A-Z0-9]{6}$/i.test(code)) continue;
  const h = hashCode(code);
  if (tier === 'VIP1') vip1.push(h);
  else if (tier === 'VIP2') vip2.push(h);
}

vip1.sort();
vip2.sort();

const outDir = path.join(root, 'src', 'entitlements');
fs.mkdirSync(outDir, { recursive: true });
const outFile = path.join(outDir, 'vipHashes.generated.ts');
const body = `/* AUTO-GENERATED by scripts/generate-vip-hashes.cjs — do not edit. Plaintext codes are not included. */
export const VIP1_HASHES: readonly string[] = ${JSON.stringify(vip1, null, 2)} as const;

export const VIP2_HASHES: readonly string[] = ${JSON.stringify(vip2, null, 2)} as const;
`;
fs.writeFileSync(outFile, body, 'utf8');
console.log(`Wrote ${outFile}`);
console.log(`VIP1=${vip1.length} VIP2=${vip2.length} from ${csvPath}`);
